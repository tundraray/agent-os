import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  Patch,
  Post,
  Query,
  Req,
  UseGuards,
} from '@nestjs/common';
import {
  RenameThreadRequestSchema,
  ThreadIdSchema,
  ThreadListQuerySchema,
  type RenameThreadRequest,
  type ThreadListQuery,
  type ThreadListResponse,
  type ThreadMessagesResponse,
  type ThreadSummary,
} from '@agent-os/contracts';
import { SessionGuard } from '../auth/session.guard.js';
import type { AuthedRequest } from '../auth/auth.types.js';
import { ZodValidationPipe } from '../common/zod-validation.pipe.js';
import { ThreadsService } from './threads.service.js';

@Controller('threads')
@UseGuards(SessionGuard)
export class ThreadsController {
  constructor(private readonly threads: ThreadsService) {}

  @Get()
  list(
    @Query(new ZodValidationPipe(ThreadListQuerySchema)) query: ThreadListQuery,
    @Req() req: AuthedRequest,
  ): Promise<ThreadListResponse> {
    return this.threads.list(req.user.id, query.cursor);
  }

  /** The request body is not read: the id is generated by the server. */
  @Post()
  @HttpCode(201)
  create(@Req() req: AuthedRequest): Promise<ThreadSummary> {
    return this.threads.create(req.user.id);
  }

  @Get(':threadId')
  get(
    @Param('threadId', new ZodValidationPipe(ThreadIdSchema)) threadId: string,
    @Req() req: AuthedRequest,
  ): Promise<ThreadSummary> {
    return this.threads.get(threadId, req.user.id);
  }

  @Get(':threadId/messages')
  messages(
    @Param('threadId', new ZodValidationPipe(ThreadIdSchema)) threadId: string,
    @Req() req: AuthedRequest,
  ): Promise<ThreadMessagesResponse> {
    return this.threads.listMessages(threadId, req.user.id);
  }

  @Patch(':threadId')
  rename(
    @Param('threadId', new ZodValidationPipe(ThreadIdSchema)) threadId: string,
    @Body(new ZodValidationPipe(RenameThreadRequestSchema))
    body: RenameThreadRequest,
    @Req() req: AuthedRequest,
  ): Promise<ThreadSummary> {
    return this.threads.rename({
      threadId,
      userId: req.user.id,
      title: body.title,
    });
  }

  @Delete(':threadId')
  @HttpCode(204)
  remove(
    @Param('threadId', new ZodValidationPipe(ThreadIdSchema)) threadId: string,
    @Req() req: AuthedRequest,
  ): Promise<void> {
    return this.threads.delete(threadId, req.user.id);
  }
}
